for (const lang of langs) {
  const path = `c:/Users/njfw2/michelstravel1/client/src/locales/${lang}.json`;
  const data = JSON.parse(fs.readFileSync(path, 'utf8'));

  // Fix help FAQs
  if (data.help) {
    Object.assign(data.help, faqData[lang]);
    // Optionally remove old nested faqs if they exist and bother you
    for (const key in data.help) {
      if (key.startsWith('faq_') && typeof data.help[key] === 'object') {
        delete data.help[key];
      }
    }
  }

  // Restore Scan
  data.scan = scanData[lang];

  fs.writeFileSync(path, JSON.stringify(data, null, 2), 'utf8');
  console.log(`${lang}.json fully restored and flattened.`);
}
